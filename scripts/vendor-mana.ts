/** Copies the path data of the Mana glyphs we use into src/assets/mana/paths.ts. Run: npm run vendor:mana */
import { readFileSync, writeFileSync, mkdirSync } from 'node:fs'
import path from 'node:path'

const SRC = path.resolve('mana-master/svg')
const OUT = path.resolve('src/assets/mana/paths.ts')
const NAMES = ['w', 'u', 'b', 'r', 'g', 'c', 'x', 'y', 'z', 's', 'e', 'p', 'tap', 'untap', 'half', 'infinity', 'chaos',
  ...Array.from({ length: 21 }, (_, i) => String(i))]

const entries: string[] = []
for (const name of NAMES) {
  const svg = readFileSync(path.join(SRC, `${name}.svg`), 'utf8')
  const ds = [...svg.matchAll(/ d="([^"]+)"/g)].map((m) => m[1])
  if (ds.length === 0) throw new Error(`no <path d> in ${name}.svg`)
  entries.push(`  ${JSON.stringify(name)}: ${JSON.stringify(ds)},`)
}
mkdirSync(path.dirname(OUT), { recursive: true })
writeFileSync(OUT, `// Generated by scripts/vendor-mana.ts from mana-master/svg (Mana font, SIL OFL 1.1). Do not edit.
// Every glyph is drawn in a 32x32 viewBox.
export const MANA_VIEWBOX = 32
export const MANA_PATHS: Record<string, string[]> = {
${entries.join('\n')}
}
`)
console.log(`wrote ${NAMES.length} glyphs to ${OUT}`)
